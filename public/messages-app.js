// Only application-owned activity formats are translated. Titles and to-do text
// are interpolated unchanged, and unrecognized legacy activity stays untouched.
export function localizedActivity(item) {
  if (item.i18n && Object.hasOwn(appMessages,item.i18n.source)) {
    const vars={...item.i18n.vars};
    if(item.i18n.source==='任务状态改为{status}' && Object.hasOwn(statusSources,vars.status))vars.status=t(statusSources[vars.status]);
    return t(item.i18n.source,vars);
  }
  const original=item.text || '';
  const prefix=original.startsWith('AI · ')?'AI · ':'';
  const text=prefix?original.slice(prefix.length):original;
  if(activitySources.has(text))return prefix+t(text);
  for(const [source,pattern] of titledActivities) {
    const match=text.match(pattern);
    if(match)return prefix+t(source,{title:match[1]});
  }
  const status=text.match(/^任务状态改为(进行中|等待中|收集中|已完成|已归档)$/);
  if(status)return prefix+t('任务状态改为{status}',{status:t(status[1])});
  return original;
}
